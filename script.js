function collectTextNodes() {
  const nodes = [];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || ["SCRIPT", "STYLE"].includes(parent.tagName)) return NodeFilter.FILTER_REJECT;
      return node.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });

  while (walker.nextNode()) {
    nodes.push({ node: walker.currentNode, value: walker.currentNode.nodeValue });
  }

  return nodes;
}

function translate(value, lang) {
  if (lang === "pt") return value;
  const trimmed = value.trim();
  const translated = en[trimmed];
  return translated ? value.replace(trimmed, translated) : value;
}

function readHash() {
  const match = window.location.hash.match(/slide-(\d+)/);
  if (!match) return 0;
  const requested = Number(match[1]) - 1;
  if (Number.isNaN(requested)) return 0;
  return Math.min(Math.max(requested, 0), slides.length - 1);
}

function slideTitle(slide) {
  const original = originalTitles.get(slide) || "Apresentação";
  return currentLang === "en" ? titleEn[original] || en[original] || original : original;
}

function setSlide(index, updateHash = true) {
  currentSlide = Math.min(Math.max(index, 0), slides.length - 1);

  slides.forEach((slide, slideIndex) => {
    const isActive = slideIndex === currentSlide;
    slide.classList.toggle("active", isActive);
    slide.setAttribute("aria-hidden", String(!isActive));
  });

  document.body.classList.toggle("is-cover", slides[currentSlide].classList.contains("cover"));
  document.body.classList.toggle("is-last", currentSlide === slides.length - 1);

  if (prevButton) prevButton.disabled = currentSlide === 0;
  if (nextButton) nextButton.disabled = currentSlide === slides.length - 1;

  document.title = `${String(currentSlide + 1).padStart(2, "0")} | ${slideTitle(slides[currentSlide])}`;
  if (updateHash) window.history.replaceState(null, "", `#slide-${currentSlide + 1}`);
}

function setLanguage(lang) {
  currentLang = lang === "en" ? "en" : "pt";
  document.documentElement.lang = currentLang === "en" ? "en" : "pt-BR";
  localStorage.setItem("deckLanguage", currentLang);

  textNodes.forEach(({ node, value }) => {
    node.nodeValue = translate(value, currentLang);
  });

  ariaLabels.forEach(({ element, value }) => {
    element.setAttribute("aria-label", translate(value, currentLang));
  });

  langButtons.forEach((button) => {
    const active = button.dataset.lang === currentLang;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  setSlide(currentSlide, false);
}

function next() {
  setSlide(currentSlide + 1);
}

function previous() {
  setSlide(currentSlide - 1);
}

prevButton?.addEventListener("click", previous);
nextButton?.addEventListener("click", next);

langButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

document.addEventListener("keydown", (event) => {
  const target = event.target;
  if (target instanceof HTMLElement && ["INPUT", "TEXTAREA", "SELECT", "BUTTON"].includes(target.tagName)) return;

  if (event.key === "ArrowRight" || event.key === "PageDown" || event.key === " ") {
    event.preventDefault();
    next();
  }

  if (event.key === "ArrowLeft" || event.key === "PageUp") {
    event.preventDefault();
    previous();
  }

  if (event.key === "Home") {
    event.preventDefault();
    setSlide(0);
  }

  if (event.key === "End") {
    event.preventDefault();
    setSlide(slides.length - 1);
  }
});

window.addEventListener("hashchange", () => setSlide(readHash(), false));

